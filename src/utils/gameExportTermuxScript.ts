export function downloadTermuxGameExportScript(params: TermuxGameExportParams): {
  scriptFilename: string;
  command: string;
  count: number;
} {
  const { scriptFilename, scriptText, count } = buildTermuxGameExportScript(params);
  const blob = new Blob([scriptText], { type: 'text/x-shellscript;charset=utf-8' });
  downloadBlob(blob, scriptFilename);
  return {
    scriptFilename,
    command: buildTermuxCharacterRunCommand(scriptFilename),
    count,
  };
}

export function formatGameBytes(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes <= 0) return '0 B';
  if (bytes >= 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
  if (bytes >= 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${bytes} B`;
}
