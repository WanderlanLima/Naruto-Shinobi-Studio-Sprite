    'def aff_mul(m1, m2):',
    '    a1, b1, tx1, c1, d1, ty1 = m1',
    '    a2, b2, tx2, c2, d2, ty2 = m2',
    '    return (',
    '        a1 * a2 + b1 * c2,',
    '        a1 * b2 + b1 * d2,',
    '        a1 * tx2 + b1 * ty2 + tx1,',
    '        c1 * a2 + d1 * c2,',
    '        c1 * b2 + d1 * d2,',
    '        c1 * tx2 + d1 * ty2 + ty1,',
    '    )',
    '',
    'def aff_inv(m):',
    '    a, b, tx, c, d, ty = m',
    '    det = a * d - b * c',
    '    if abs(det) < 1e-8:',
    '        return None',
    '    inv_d = 1.0 / det',
    '    ia = d * inv_d',
    '    ib = -b * inv_d',
    '    ic = -c * inv_d',
    '    id_ = a * inv_d',
    '    return (ia, ib, -(ia * tx + ib * ty), ic, id_, -(ic * tx + id_ * ty))',
    '',
