    '            dst[:, :, :3] = src_pm * (1.0 - dst_a) + dst_pm * (1.0 - src_a) + (src_a * dst_a) * (d_rgb * src_rgb)',
    '            dst[:, :, 3:4] = src_a + dst_a * (1.0 - src_a)',
    '        elif blend == "screen":',
    '            d_rgb = np.divide(dst_pm, np.maximum(dst_a, 1e-6))',
