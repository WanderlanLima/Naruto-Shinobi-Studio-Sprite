    '            dst[:, :, 3:4] = src_a + dst_a * (1.0 - src_a)',
    '        else:',
    '            inv_sa = 1.0 - src_a',
    '            dst[:, :, :3] = src_pm + dst_pm * inv_sa',
    '            dst[:, :, 3:4] = src_a + dst_a * inv_sa',
