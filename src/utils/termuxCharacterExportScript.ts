    '        y0 = max(0, int(math.floor(float(tc[1].min()))) - 1)',
    '        x1 = min(cw, int(math.ceil(float(tc[0].max()))) + 1)',
    '        y1 = min(ch, int(math.ceil(float(tc[1].max()))) + 1)',
