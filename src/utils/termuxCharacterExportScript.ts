    '        if sr < 248 or sg < 248 or sb < 248:',
    '            src_rgb = src_rgb * np.array([sr / 255.0, sg / 255.0, sb / 255.0], dtype=np.float32)',
    '        src_pm = src_rgb * src_a',
    '        dst = canvas_pm[y0:y1, x0:x1]',
    '        dst_pm = dst[:, :, :3]',
    '        dst_a = dst[:, :, 3:4]',
    '        blend = slot.get("blend") or "normal"',
