function resolveCharacterOrigin(
  ninja: NinjaEntry,
  mediaProfile?: NinjaMediaProfile | null
): string {
  if (mediaProfile?.originBase && /^https?:\/\//i.test(mediaProfile.originBase)) {
    return mediaProfile.originBase.replace(/\/+$/, '');
  }
  try {
    return new URL(ninja.atlasUrl).origin;
  } catch {
    return 'https://naruto.jotagame.com';
  }
}

function utf8ToBase64(text: string): string {
  const bytes = new TextEncoder().encode(text);
  let binary = '';
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) {
    binary += String.fromCharCode(...bytes.subarray(i, i + CHUNK));
  }
  return btoa(binary);
}

