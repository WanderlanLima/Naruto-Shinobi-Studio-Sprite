    '        asy = float(att_info.get("scaleY") if att_info.get("scaleY") is not None else 1.0)',
    '        aw = float(att_info.get("width") or out_w)',
    '        ah = float(att_info.get("height") or out_h)',
    '        ca, sa_r = math.cos(arot), math.sin(arot)',
